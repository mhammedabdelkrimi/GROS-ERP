CREATE TABLE devis (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero VARCHAR2(30) NOT NULL UNIQUE,
  client_id NUMBER NOT NULL REFERENCES client(id),
  statut VARCHAR2(20) DEFAULT 'BROUILLON' NOT NULL CHECK (statut IN ('BROUILLON','ENVOYE','ACCEPTE','REFUSE','CONVERTI')),
  date_creation TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  date_validite DATE NOT NULL,
  montant_ht NUMBER(15,2) DEFAULT 0 NOT NULL,
  montant_tva NUMBER(15,2) DEFAULT 0 NOT NULL,
  montant_ttc NUMBER(15,2) DEFAULT 0 NOT NULL,
  commande_id NUMBER REFERENCES commande_client(id),
  cree_par NUMBER REFERENCES utilisateur(id)
);

CREATE TABLE ligne_devis (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  devis_id NUMBER NOT NULL REFERENCES devis(id),
  produit_id NUMBER NOT NULL REFERENCES produit(id),
  quantite NUMBER(10) NOT NULL CHECK (quantite > 0),
  prix_unitaire NUMBER(15,2) NOT NULL CHECK (prix_unitaire >= 0),
  taux_tva NUMBER(5,2) NOT NULL
);

CREATE TABLE tournee (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero VARCHAR2(30) NOT NULL UNIQUE,
  date_tournee DATE NOT NULL,
  livreur_id NUMBER NOT NULL REFERENCES utilisateur(id),
  statut VARCHAR2(20) DEFAULT 'PLANIFIEE' NOT NULL CHECK (statut IN ('PLANIFIEE','EN_COURS','TERMINEE')),
  cree_par NUMBER REFERENCES utilisateur(id),
  date_creation TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE tournee_bon (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tournee_id NUMBER NOT NULL REFERENCES tournee(id),
  bon_livraison_id NUMBER NOT NULL REFERENCES bon_livraison(id),
  CONSTRAINT uk_tournee_bon UNIQUE (bon_livraison_id)
);

CREATE INDEX idx_tournee_livreur ON tournee(livreur_id, date_tournee);
CREATE INDEX idx_tournee_bon_tournee ON tournee_bon(tournee_id);