CREATE TABLE paiement (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id NUMBER NOT NULL REFERENCES client(id),
  montant NUMBER(15,2) NOT NULL CHECK (montant > 0),
  mode_paiement VARCHAR2(10) NOT NULL CHECK (mode_paiement IN ('ESPECES','CHEQUE','VIREMENT')),
  date_reglement DATE DEFAULT SYSDATE NOT NULL,
  cree_par NUMBER REFERENCES utilisateur(id)
);

CREATE TABLE affectation_paiement (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paiement_id NUMBER NOT NULL REFERENCES paiement(id),
  facture_id NUMBER NOT NULL REFERENCES facture_client(id),
  montant_affecte NUMBER(15,2) NOT NULL CHECK (montant_affecte > 0)
);