CREATE TABLE utilisateur (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nom VARCHAR2(100) NOT NULL,
  email VARCHAR2(150) NOT NULL UNIQUE,
  mot_de_passe_hache VARCHAR2(100) NOT NULL,
  role_nom VARCHAR2(30) NOT NULL CHECK (role_nom IN ('ADMINISTRATEUR','DIRECTEUR','RESPONSABLE_ACHATS','COMMERCIAL','MAGASINIER','LIVREUR','SECRETAIRE_CAISSIER','COMPTABLE')),
  actif BOOLEAN DEFAULT TRUE NOT NULL,
  tentatives_echouees NUMBER(3) DEFAULT 0 NOT NULL,
  verrouille_jusqua TIMESTAMP
);

CREATE TABLE journal_audit (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  utilisateur_id NUMBER REFERENCES utilisateur(id),
  action VARCHAR2(50) NOT NULL,
  entite VARCHAR2(50) NOT NULL,
  entite_id NUMBER,
  date_heure TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE parametre (
  cle VARCHAR2(50) PRIMARY KEY,
  valeur VARCHAR2(200) NOT NULL
);

CREATE TABLE compteur (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type_doc VARCHAR2(10) NOT NULL,
  annee NUMBER(4) NOT NULL,
  derniere_valeur NUMBER DEFAULT 0 NOT NULL,
  CONSTRAINT uk_compteur UNIQUE (type_doc, annee)
);

