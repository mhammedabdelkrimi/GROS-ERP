CREATE TABLE categorie (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nom VARCHAR2(100) NOT NULL UNIQUE
);

CREATE TABLE produit (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference VARCHAR2(30) NOT NULL UNIQUE,
  designation VARCHAR2(200) NOT NULL,
  categorie_id NUMBER REFERENCES categorie(id),
  unite VARCHAR2(20) DEFAULT 'PIECE' NOT NULL,
  prix_achat NUMBER(15,2) NOT NULL CHECK (prix_achat >= 0),
  prix_vente NUMBER(15,2) NOT NULL CHECK (prix_vente >= 0),
  taux_tva NUMBER(5,2) DEFAULT 20 NOT NULL CHECK (taux_tva BETWEEN 0 AND 100),
  seuil_alerte NUMBER(10) DEFAULT 0 NOT NULL,
  perissable BOOLEAN DEFAULT FALSE NOT NULL,
  actif BOOLEAN DEFAULT TRUE NOT NULL
);

CREATE TABLE historique_prix (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  produit_id NUMBER NOT NULL REFERENCES produit(id),
  ancien_prix NUMBER(15,2) NOT NULL,
  nouveau_prix NUMBER(15,2) NOT NULL,
  date_changement TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  modifie_par NUMBER REFERENCES utilisateur(id)
);

CREATE TABLE client (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raison_sociale VARCHAR2(150) NOT NULL,
  adresse VARCHAR2(250),
  telephone VARCHAR2(30),
  limite_credit NUMBER(15,2) DEFAULT 0 NOT NULL CHECK (limite_credit >= 0),
  delai_paiement_jours NUMBER(3) DEFAULT 30 NOT NULL,
  bloque BOOLEAN DEFAULT FALSE NOT NULL,
  actif BOOLEAN DEFAULT TRUE NOT NULL
);

CREATE TABLE fournisseur (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raison_sociale VARCHAR2(150) NOT NULL,
  adresse VARCHAR2(250),
  telephone VARCHAR2(30),
  conditions_paiement VARCHAR2(100),
  delai_livraison_jours NUMBER(3) DEFAULT 7 NOT NULL,
  actif BOOLEAN DEFAULT TRUE NOT NULL
);