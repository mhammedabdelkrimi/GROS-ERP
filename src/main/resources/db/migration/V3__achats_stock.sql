CREATE TABLE lot (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  produit_id NUMBER NOT NULL REFERENCES produit(id),
  numero VARCHAR2(50) NOT NULL,
  date_peremption DATE,
  quantite_restante NUMBER(10) NOT NULL CHECK (quantite_restante >= 0),
  date_entree TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE mouvement_stock (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  produit_id NUMBER NOT NULL REFERENCES produit(id),
  lot_id NUMBER REFERENCES lot(id),
  type_mouvement VARCHAR2(30) NOT NULL CHECK (type_mouvement IN ('ENTREE_ACHAT','SORTIE_VENTE','RETOUR_CLIENT','CASSE','CORRECTION_INVENTAIRE')),
  quantite NUMBER(10) NOT NULL CHECK (quantite <> 0),
  document_type VARCHAR2(30) NOT NULL,
  document_id NUMBER NOT NULL,
  date_mouvement TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  auteur_id NUMBER REFERENCES utilisateur(id)
);

CREATE TABLE commande_fournisseur (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero VARCHAR2(30) NOT NULL UNIQUE,
  fournisseur_id NUMBER NOT NULL REFERENCES fournisseur(id),
  statut VARCHAR2(30) DEFAULT 'BROUILLON' NOT NULL CHECK (statut IN ('BROUILLON','A_VALIDER','VALIDEE','PARTIELLEMENT_RECUE','RECUE','ANNULEE')),
  montant_total NUMBER(15,2) DEFAULT 0 NOT NULL,
  cree_par NUMBER REFERENCES utilisateur(id),
  date_creation TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE ligne_cmd_fournisseur (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  commande_id NUMBER NOT NULL REFERENCES commande_fournisseur(id),
  produit_id NUMBER NOT NULL REFERENCES produit(id),
  quantite NUMBER(10) NOT NULL CHECK (quantite > 0),
  quantite_recue NUMBER(10) DEFAULT 0 NOT NULL,
  prix_unitaire NUMBER(15,2) NOT NULL CHECK (prix_unitaire >= 0)
);

CREATE TABLE reception (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero VARCHAR2(30) NOT NULL UNIQUE,
  commande_id NUMBER NOT NULL REFERENCES commande_fournisseur(id),
  date_reception TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  cree_par NUMBER REFERENCES utilisateur(id)
);

CREATE TABLE ligne_reception (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reception_id NUMBER NOT NULL REFERENCES reception(id),
  produit_id NUMBER NOT NULL REFERENCES produit(id),
  quantite_recue NUMBER(10) NOT NULL CHECK (quantite_recue > 0),
  numero_lot VARCHAR2(50) NOT NULL,
  date_peremption DATE
);

CREATE TABLE facture_fournisseur (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero_fournisseur VARCHAR2(50) NOT NULL,
  commande_id NUMBER NOT NULL REFERENCES commande_fournisseur(id),
  date_echeance DATE NOT NULL,
  montant NUMBER(15,2) NOT NULL,
  payee BOOLEAN DEFAULT FALSE NOT NULL
);

CREATE TABLE inventaire (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date_inventaire DATE NOT NULL,
  cloture BOOLEAN DEFAULT FALSE NOT NULL
);

CREATE TABLE ligne_inventaire (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inventaire_id NUMBER NOT NULL REFERENCES inventaire(id),
  produit_id NUMBER NOT NULL REFERENCES produit(id),
  quantite_theorique NUMBER(10) NOT NULL,
  quantite_comptee NUMBER(10) NOT NULL,
  justification VARCHAR2(250)
);