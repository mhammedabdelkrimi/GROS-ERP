DELETE FROM facture_fournisseur;
ALTER TABLE facture_fournisseur DROP COLUMN payee;
ALTER TABLE facture_fournisseur RENAME COLUMN montant TO montant_ttc;

ALTER TABLE facture_fournisseur ADD (
  numero VARCHAR2(30) NOT NULL,
  fournisseur_id NUMBER NOT NULL REFERENCES fournisseur(id),
  date_facture DATE NOT NULL,
  montant_ht NUMBER(15,2) NOT NULL,
  montant_tva NUMBER(15,2) NOT NULL,
  montant_paye NUMBER(15,2) DEFAULT 0 NOT NULL,
  statut VARCHAR2(25) DEFAULT 'A_PAYER' NOT NULL CHECK (statut IN ('A_PAYER','PARTIELLEMENT_PAYEE','PAYEE')),
  cree_par NUMBER REFERENCES utilisateur(id),
  date_creation TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

ALTER TABLE facture_fournisseur ADD CONSTRAINT uk_ff_numero UNIQUE (numero);
ALTER TABLE facture_fournisseur ADD CONSTRAINT uk_ff_fournisseur UNIQUE (fournisseur_id, numero_fournisseur);
ALTER TABLE facture_fournisseur ADD CONSTRAINT ck_ff_montants
  CHECK (montant_ht >= 0 AND montant_tva >= 0 AND montant_paye >= 0 AND montant_paye <= montant_ttc);

CREATE TABLE paiement_fournisseur (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  facture_id NUMBER NOT NULL REFERENCES facture_fournisseur(id),
  montant NUMBER(15,2) NOT NULL CHECK (montant > 0),
  mode_paiement VARCHAR2(10) NOT NULL CHECK (mode_paiement IN ('ESPECES','CHEQUE','VIREMENT')),
  date_reglement DATE DEFAULT SYSDATE NOT NULL,
  cree_par NUMBER REFERENCES utilisateur(id)
);
CREATE INDEX idx_pf_facture ON paiement_fournisseur(facture_id);