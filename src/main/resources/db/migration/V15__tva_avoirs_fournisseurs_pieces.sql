CREATE TABLE avoir_fournisseur (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero VARCHAR2(30) NOT NULL UNIQUE,
  numero_fournisseur VARCHAR2(50) NOT NULL,
  facture_id NUMBER NOT NULL REFERENCES facture_fournisseur(id),
  fournisseur_id NUMBER NOT NULL REFERENCES fournisseur(id),
  motif VARCHAR2(250) NOT NULL,
  montant_ht NUMBER(15,2) NOT NULL CHECK (montant_ht > 0),
  montant_tva NUMBER(15,2) NOT NULL CHECK (montant_tva >= 0),
  montant_ttc NUMBER(15,2) NOT NULL,
  date_avoir DATE NOT NULL,
  cree_par NUMBER REFERENCES utilisateur(id),
  date_creation TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uk_af_fournisseur UNIQUE (fournisseur_id, numero_fournisseur)
);
CREATE INDEX idx_af_facture ON avoir_fournisseur(facture_id);

