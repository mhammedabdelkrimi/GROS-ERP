CREATE TABLE ecriture_comptable (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero VARCHAR2(30) NOT NULL UNIQUE,
  date_ecriture DATE DEFAULT SYSDATE NOT NULL,
  libelle VARCHAR2(250) NOT NULL,
  piece_type VARCHAR2(30) NOT NULL,
  piece_id NUMBER NOT NULL,
  extourne_de NUMBER,
  cree_par NUMBER REFERENCES utilisateur(id),
  date_creation TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_ecriture_extourne FOREIGN KEY (extourne_de) REFERENCES ecriture_comptable(id),
  CONSTRAINT uk_ecriture_extourne UNIQUE (extourne_de)
);

CREATE TABLE ligne_ecriture (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ecriture_id NUMBER NOT NULL REFERENCES ecriture_comptable(id),
  compte_numero VARCHAR2(10) NOT NULL REFERENCES compte_comptable(numero),
  debit NUMBER(15,2) DEFAULT 0 NOT NULL,
  credit NUMBER(15,2) DEFAULT 0 NOT NULL,
  CONSTRAINT ck_ligne_ecriture CHECK (debit >= 0 AND credit >= 0 AND (debit = 0 OR credit = 0) AND debit + credit > 0)
);

CREATE INDEX idx_ecriture_piece ON ecriture_comptable(piece_type, piece_id);
CREATE INDEX idx_ligne_ecriture ON ligne_ecriture(ecriture_id);
CREATE INDEX idx_ligne_compte ON ligne_ecriture(compte_numero);

CREATE OR REPLACE TRIGGER trg_ecriture_immuable
BEFORE UPDATE OR DELETE ON ecriture_comptable
BEGIN
  RAISE_APPLICATION_ERROR(-20002, 'Une ecriture comptable ne peut pas etre modifiee ni supprimee');
END;
