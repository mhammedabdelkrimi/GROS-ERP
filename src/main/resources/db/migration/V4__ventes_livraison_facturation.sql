CREATE TABLE commande_client (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero VARCHAR2(30) NOT NULL UNIQUE,
  client_id NUMBER NOT NULL REFERENCES client(id),
  statut VARCHAR2(20) DEFAULT 'BROUILLON' NOT NULL CHECK (statut IN ('BROUILLON','VALIDEE','EN_PREPARATION','LIVREE','FACTUREE','ANNULEE')),
  montant_ht NUMBER(15,2) DEFAULT 0 NOT NULL,
  montant_tva NUMBER(15,2) DEFAULT 0 NOT NULL,
  montant_ttc NUMBER(15,2) DEFAULT 0 NOT NULL,
  cree_par NUMBER REFERENCES utilisateur(id),
  date_creation TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE ligne_commande_client (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  commande_id NUMBER NOT NULL REFERENCES commande_client(id),
  produit_id NUMBER NOT NULL REFERENCES produit(id),
  quantite NUMBER(10) NOT NULL CHECK (quantite > 0),
  prix_unitaire NUMBER(15,2) NOT NULL,
  remise_pourcent NUMBER(5,2) DEFAULT 0 NOT NULL CHECK (remise_pourcent BETWEEN 0 AND 100),
  taux_tva NUMBER(5,2) NOT NULL
);

CREATE TABLE bon_livraison (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero VARCHAR2(30) NOT NULL UNIQUE,
  commande_id NUMBER NOT NULL REFERENCES commande_client(id),
  statut VARCHAR2(10) DEFAULT 'CREE' NOT NULL CHECK (statut IN ('CREE','CONFIRME','REFUSE')),
  signe_par_client BOOLEAN DEFAULT FALSE NOT NULL,
  date_signature TIMESTAMP,
  motif_refus VARCHAR2(250)
);

CREATE TABLE facture_client (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero VARCHAR2(30) NOT NULL UNIQUE,
  bon_livraison_id NUMBER NOT NULL REFERENCES bon_livraison(id),
  client_id NUMBER NOT NULL REFERENCES client(id),
  date_emission DATE DEFAULT SYSDATE NOT NULL,
  date_echeance DATE NOT NULL,
  montant_ht NUMBER(15,2) NOT NULL,
  montant_tva NUMBER(15,2) NOT NULL,
  montant_ttc NUMBER(15,2) NOT NULL,
  montant_paye NUMBER(15,2) DEFAULT 0 NOT NULL,
  statut VARCHAR2(20) DEFAULT 'EMISE' NOT NULL CHECK (statut IN ('EMISE','PARTIELLEMENT_PAYEE','PAYEE','ANNULEE')),
  CONSTRAINT ck_paye CHECK (montant_paye <= montant_ttc)
);

CREATE TABLE ligne_facture (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  facture_id NUMBER NOT NULL REFERENCES facture_client(id),
  produit_id NUMBER NOT NULL REFERENCES produit(id),
  designation VARCHAR2(200) NOT NULL,
  quantite NUMBER(10) NOT NULL,
  prix_unitaire NUMBER(15,2) NOT NULL,
  remise_pourcent NUMBER(5,2) DEFAULT 0 NOT NULL,
  taux_tva NUMBER(5,2) NOT NULL
);

CREATE TABLE avoir (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero VARCHAR2(30) NOT NULL UNIQUE,
  facture_id NUMBER NOT NULL REFERENCES facture_client(id),
  motif VARCHAR2(250) NOT NULL,
  montant NUMBER(15,2) NOT NULL CHECK (montant > 0),
  date_creation TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);