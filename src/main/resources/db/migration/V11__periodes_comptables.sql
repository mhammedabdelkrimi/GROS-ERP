CREATE TABLE periode_comptable (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  annee NUMBER(4) NOT NULL,
  mois NUMBER(2) NOT NULL CHECK (mois BETWEEN 1 AND 12),
  tva_facturee NUMBER(15,2) NOT NULL,
  tva_recuperable NUMBER(15,2) NOT NULL,
  tva_due NUMBER(15,2) NOT NULL,
  cloture_par NUMBER REFERENCES utilisateur(id),
  date_cloture TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uk_periode UNIQUE (annee, mois)
);